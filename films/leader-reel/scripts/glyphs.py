#!/usr/bin/env python3
"""Extract Archivo glyph outlines at fixed variable instances (fontTools instancer).

Output: src/data/glyphs.js -> window.GLYPHS = { instances: { "900x125": {upm, ascender, descender, capHeight,
glyphs: {ch: {adv, bbox:[x0,y0,x1,y1], cmds:[[op,...]]}}, word:{text, adv:[...]} } } }
Coordinates are font units, y-down (screen space). Ops: M L Q C Z.
"""
import json, os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.recordingPen import RecordingPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets/fonts/archivo-latin-standard-normal.woff2")
INSTANCES = {"900x125": {"wght": 900, "wdth": 125}, "900x62": {"wght": 900, "wdth": 62}, "600x100": {"wght": 600, "wdth": 100}}
CHARS = "0123456789SHOWREL"
WORD = "SHOWREEL"

def r(v):
    return round(float(v), 2)

out = {"instances": {}}
for key, axes in INSTANCES.items():
    f = TTFont(SRC)
    inst = instancer.instantiateVariableFont(f, axes, inplace=False)
    gs = inst.getGlyphSet()
    cmap = inst.getBestCmap()
    hmtx = inst["hmtx"].metrics
    os2 = inst["OS/2"]
    data = {"upm": inst["head"].unitsPerEm, "ascender": inst["hhea"].ascent, "descender": inst["hhea"].descent,
            "capHeight": getattr(os2, "sCapHeight", 0), "xHeight": getattr(os2, "sxHeight", 0), "glyphs": {}}
    for ch in CHARS:
        gname = cmap[ord(ch)]
        pen = RecordingPen()
        gs[gname].draw(pen)
        cmds = []
        for op, args in pen.value:
            if op == "moveTo":
                (x, y), = args; cmds.append(["M", r(x), r(-y)])
            elif op == "lineTo":
                (x, y), = args; cmds.append(["L", r(x), r(-y)])
            elif op == "qCurveTo":
                # TrueType quadratic spline: implied on-curve points between consecutive off-curve points
                pts = list(args)
                if pts[-1] is None:
                    raise SystemExit("closed quad contour without on-curve point not supported")
                offs, end = pts[:-1], pts[-1]
                for i, c in enumerate(offs):
                    if i < len(offs) - 1:
                        n = offs[i + 1]
                        mid = ((c[0] + n[0]) / 2, (c[1] + n[1]) / 2)
                        cmds.append(["Q", r(c[0]), r(-c[1]), r(mid[0]), r(-mid[1])])
                    else:
                        cmds.append(["Q", r(c[0]), r(-c[1]), r(end[0]), r(-end[1])])
                if not offs:
                    cmds.append(["L", r(end[0]), r(-end[1])])
            elif op == "curveTo":
                (a, b, c) = args; cmds.append(["C", r(a[0]), r(-a[1]), r(b[0]), r(-b[1]), r(c[0]), r(-c[1])])
            elif op in ("closePath", "endPath"):
                cmds.append(["Z"])
            else:
                raise SystemExit("unknown pen op " + op)
        bp = BoundsPen(gs)
        gs[gname].draw(bp)
        x0, y0, x1, y1 = bp.bounds
        data["glyphs"][ch] = {"adv": hmtx[gname][0], "bbox": [r(x0), r(-y1), r(x1), r(-y0)], "cmds": cmds}
    # kerned advances for the lockup word (GPOS pair kerning is applied at draw time by the browser; record raw advances)
    data["word"] = {"text": WORD, "adv": [hmtx[cmap[ord(c)]][0] for c in WORD]}
    out["instances"][key] = data

os.makedirs(os.path.join(ROOT, "src/data"), exist_ok=True)
with open(os.path.join(ROOT, "src/data/glyphs.js"), "w") as fh:
    fh.write("// generated by scripts/glyphs.py — Archivo (SIL OFL) outlines at fixed instances\nwindow.GLYPHS = ")
    json.dump(out, fh, separators=(",", ":"))
    fh.write(";\n")
i = out["instances"]["900x125"]
print("upm", i["upm"], "cap", i["capHeight"], "asc", i["ascender"], "desc", i["descender"])
for ch in "8765432":
    g = i["glyphs"][ch]
    print(ch, "adv", g["adv"], "bbox", g["bbox"], "cmds", len(g["cmds"]))
print("SHOWREEL adv", i["word"]["adv"], sum(i["word"]["adv"]))
