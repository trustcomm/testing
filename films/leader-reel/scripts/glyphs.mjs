#!/usr/bin/env node
// Extracts Archivo glyph outlines (variable instance wght 900 / wdth 125) for the numerals and the lockup letters.
// Output: src/data/glyphs.js → window.GLYPHS = { upm, ascender, descender, capHeight, xHeight, glyphs: { ch: { adv, bbox, cmds } } }
// cmds are in font units, y-down (screen space), as [op, ...coords] with op ∈ M L Q C Z.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(ROOT, "tools", "x.js"));
const fontkit = require("fontkit");

const base = fontkit.openSync(join(ROOT, "assets/fonts/archivo-latin-standard-normal.woff2"));
const out = { instances: {} };
const INSTANCES = { "900x125": { wght: 900, wdth: 125 }, "900x62": { wght: 900, wdth: 62 }, "600x100": { wght: 600, wdth: 100 } };
const CHARS = "0123456789SHOWREL";
const r = (v) => Math.round(v * 100) / 100;
for (const [key, axes] of Object.entries(INSTANCES)) {
  const f = base.getVariation(axes);
  const inst = { upm: f.unitsPerEm, ascender: f.ascent, descender: f.descent, capHeight: f.capHeight, xHeight: f.xHeight, glyphs: {} };
  for (const ch of CHARS) {
    const run = f.layout(ch);
    const g = run.glyphs[0];
    const cmds = g.path.commands.map((c) => {
      const a = c.args;
      switch (c.command) {
        case "moveTo": return ["M", r(a[0]), r(-a[1])];
        case "lineTo": return ["L", r(a[0]), r(-a[1])];
        case "quadraticCurveTo": return ["Q", r(a[0]), r(-a[1]), r(a[2]), r(-a[3])];
        case "bezierCurveTo": return ["C", r(a[0]), r(-a[1]), r(a[2]), r(-a[3]), r(a[4]), r(-a[5])];
        case "closePath": return ["Z"];
        default: throw new Error("unknown command " + c.command);
      }
    });
    const bb = g.path.bbox; // y-up
    inst.glyphs[ch] = { adv: r(run.positions[0].xAdvance), bbox: [r(bb.minX), r(-bb.maxY), r(bb.maxX), r(-bb.minY)], cmds };
  }
  // kerning pairs for the lockup word
  const word = "SHOWREEL";
  const lay = f.layout(word);
  inst.word = { text: word, adv: lay.positions.map((p) => r(p.xAdvance)) };
  out.instances[key] = inst;
}
writeFileSync(join(ROOT, "src/data/glyphs.js"), "// generated by scripts/glyphs.mjs — Archivo (SIL OFL) outlines\nwindow.GLYPHS = " + JSON.stringify(out) + ";\n");
const i = out.instances["900x125"];
console.log("upm", i.upm, "cap", i.capHeight, "asc", i.ascender, "desc", i.descender);
for (const ch of "8765432") console.log(ch, "adv", i.glyphs[ch].adv, "bbox", i.glyphs[ch].bbox.join(","), "cmds", i.glyphs[ch].cmds.length);
console.log("SHOWREEL adv", i.word.adv.join(" "), "sum", i.word.adv.reduce((a, b) => a + b, 0));
